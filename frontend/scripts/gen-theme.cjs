// Generates src/theme.css: every Tailwind color family the app uses, as RGB
// triplets on CSS variables. `:root` holds the stock (light) values that the
// visitor widget renders with; `.cave` remaps them to the dark dashboard theme.
// Run: node scripts/gen-theme.cjs
const fs = require('fs')
const path = require('path')
const tw = require('tailwindcss/colors')

const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']
const ACCENTS = ['red', 'amber', 'emerald', 'green', 'violet', 'sky', 'teal', 'indigo', 'yellow', 'orange', 'rose']

const BRAND_LIGHT = {
  50: '#f0f4ff', 100: '#dde6ff', 200: '#c3d1ff', 300: '#9bb1fd', 400: '#6f88fa',
  500: '#4f6ef7', 600: '#3b55e8', 700: '#2e44cc', 800: '#2738a5', 900: '#243482', 950: '#1a2150',
}

// Dark neutrals: page #090a0b, surfaces #111111, hairlines #23262a.
const NEUTRAL_DARK = {
  50: '#0a0a0b', 100: '#171819', 200: '#23262a', 300: '#383838', 400: '#6b6b6b',
  500: '#8f8f8f', 600: '#a3a3a3', 700: '#c9c9c9', 800: '#dddddd', 900: '#ededed', 950: '#fafafa',
}
// Monochrome accent: primary actions are near-white with dark text.
const BRAND_DARK = {
  50: '#161616', 100: '#262626', 200: '#383838', 300: '#5c5c5c', 400: '#cfcfcf',
  500: '#f3f3f3', 600: '#ffffff', 700: '#e8e8e8', 800: '#f3f3f3', 900: '#fafafa', 950: '#ffffff',
}
const SURFACE_DARK = '#111111'
const PAGE_DARK = '#090a0b'

const hex = (h) => {
  const n = parseInt(h.replace('#', ''), 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}
const trip = (rgb) => rgb.join(' ')
const mix = (a, b, t) => hex(a).map((v, i) => Math.round(v * (1 - t) + hex(b)[i] * t))

// Tinted accent scale for dark: low steps become translucent-looking tints of
// the hue over the surface, high steps become the light end of the hue.
function darkAccent(scale) {
  return {
    50: mix(SURFACE_DARK, scale[500], 0.12),
    100: mix(SURFACE_DARK, scale[500], 0.18),
    200: mix(SURFACE_DARK, scale[500], 0.28),
    300: mix(SURFACE_DARK, scale[500], 0.42),
    400: hex(scale[400]),
    500: hex(scale[400]),
    600: hex(scale[400]),
    700: hex(scale[300]),
    800: hex(scale[200]),
    900: hex(scale[100]),
    950: hex(scale[50]),
  }
}

const block = (sel, vars) => `${sel} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}\n`

const light = { white: trip(hex('#ffffff')), page: trip(hex('#fafafa')) }
const dark = { white: trip(hex(SURFACE_DARK)), page: trip(hex(PAGE_DARK)) }
for (const s of STEPS) {
  light[`zinc-${s}`] = trip(hex(tw.zinc[s]))
  light[`gray-${s}`] = trip(hex(tw.gray[s]))
  light[`brand-${s}`] = trip(hex(BRAND_LIGHT[s]))
  dark[`zinc-${s}`] = trip(hex(NEUTRAL_DARK[s]))
  dark[`gray-${s}`] = trip(hex(NEUTRAL_DARK[s]))
  dark[`brand-${s}`] = trip(hex(BRAND_DARK[s]))
}
for (const name of ACCENTS) {
  const d = darkAccent(tw[name])
  for (const s of STEPS) {
    light[`${name}-${s}`] = trip(hex(tw[name][s]))
    dark[`${name}-${s}`] = trip(d[s])
  }
}

const out =
  '/* Generated by scripts/gen-theme.cjs. Edit the script, not this file. */\n\n' +
  block(':root, .light-scope', light) +
  '\n' +
  block('.cave', dark).replace(/\n}\n$/, '\n  color-scheme: dark;\n}\n') +
  '\n/* Anything that must look the way visitors see it (the widget preview) opts back out. */\n' +
  '.cave .light-scope { color-scheme: light; }\n'

fs.writeFileSync(path.join(__dirname, '../src/theme.css'), out)
console.log('wrote src/theme.css')
